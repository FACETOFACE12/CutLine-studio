import React, { useState, useMemo } from 'react';
import { AssetGovernanceView } from './components/AssetGovernanceView';
import { ColorAndCodecView } from './components/ColorAndCodecView';
import { DiagnosticsAndThermalView } from './components/DiagnosticsAndThermalView';
import { AiAssistantView } from './components/AiAssistantView';
import {
  HardwareTelemetryInput,
  evaluateHardwareTelemetry,
  generateStandardFolderStructure
} from './utils/postProductionEngine';
import { X, Copy, Check, Download } from 'lucide-react';

type ActiveWorkspace = 'assets' | 'color' | 'diagnostics' | 'assistant';

export default function App() {
  const [activeTab, setActiveTab] = useState<ActiveWorkspace>('assets');
  const [projectCode, setProjectCode] = useState<string>('ORION26');
  const [showTurnoverModal, setShowTurnoverModal] = useState<boolean>(false);
  const [copiedTurnover, setCopiedTurnover] = useState<boolean>(false);

  const [telemetry, setTelemetry] = useState<HardwareTelemetryInput>({
    gpuTempC: 68,
    cpuTempC: 71,
    vramUsedGb: 14,
    vramTotalGb: 24,
    ramUsedGb: 36,
    ramTotalGb: 64,
    storageReadMbps: 850,
    activeStreams: 2,
    activeCodecType: 'Intra-frame'
  });

  const hardwareSummary = useMemo(() => evaluateHardwareTelemetry(telemetry), [telemetry]);

  const turnoverDocument = useMemo(() => {
    const folders = generateStandardFolderStructure(projectCode, 3, ['A_CAM', 'B_CAM']);
    return [
      `====================================================================`,
      `HOLLYWOOD / COMMERCIAL POST-PRODUCTION TURNOVER SPECIFICATION`,
      `Project Code : ${projectCode}`,
      `Generated By : CutLine Senior AI Assistant Editor Workbench`,
      `====================================================================`,
      ``,
      `[1. DIRECTORY HIERARCHY & ASSET GOVERNANCE]`,
      ...folders.map((f) => `- /${projectCode}/${f.code} (${f.namingRule})`),
      ``,
      `[2. TIMECODE, AUDIO & PROXY STANDARDS]`,
      `- Master Edit Timebase : 23.976 fps / 24.000 fps (Zero Pull-down Drift Permitted)`,
      `- Offline Proxy Spec   : Apple ProRes 422 Proxy / DNxHR LB (1920x1080 Intra-frame)`,
      `- Production Audio     : 48,000 Hz / 24-bit Uncompressed Broadcast WAV (BWF)`,
      `- Sound Turnover AAF   : 48f Handles, Split Tracks by Role (DX / AMB / SFX / MX), 2-Pop @ 00:59:58:00`,
      ``,
      `[3. COLOR MANAGEMENT & MASTER DELIVERY]`,
      `- Working Color Space  : DaVinci Wide Gamut / Intermediate or ACEScct 1.3`,
      `- Broadcast Delivery   : Rec.709 / Gamma 2.4 (NCLC 1-1-1 Rec.709-A Tag for macOS QuickTime)`,
      `- DI / Online Master   : Apple ProRes 422 HQ / ProRes 4444 (.mov)`,
      ``,
      `[4. WORKSTATION TELEMETRY SNAPSHOT]`,
      `- Status: ${hardwareSummary.overallStatus.toUpperCase()} | GPU: ${telemetry.gpuTempC}°C | CPU: ${telemetry.cpuTempC}°C | VRAM: ${hardwareSummary.vramUsagePercent}%`
    ].join('\n');
  }, [projectCode, hardwareSummary, telemetry]);

  const handleCopyTurnover = () => {
    navigator.clipboard?.writeText(turnoverDocument).catch(() => {});
    setCopiedTurnover(true);
    setTimeout(() => setCopiedTurnover(false), 1800);
  };

  const handleDownloadTurnover = () => {
    const blob = new Blob([turnoverDocument], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${projectCode}_POST_TURNOVER_SPEC_v01.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="min-h-screen bg-[#090d16] text-slate-100 flex flex-col">
      {/* Strict 3-Zone Top Bar Contract */}
      <header className="flex items-center justify-between gap-8 px-6 py-4 border-b border-slate-800/90 bg-slate-950/90 sticky top-0 z-30 backdrop-blur">
        {/* Zone 1: Brand Title (Single text element wordmark) */}
        <a
          href="#top"
          onClick={(e) => {
            e.preventDefault();
            setActiveTab('assets');
          }}
          className="text-lg font-bold tracking-tight text-slate-100 whitespace-nowrap shrink-0"
        >
          CutLine Studio
        </a>

        {/* Zone 2: 4 Concise Single-Line Navigation Links */}
        <nav aria-label="主工作区导航" className="flex items-center gap-6 text-sm font-medium text-slate-400 overflow-x-auto">
          <button
            type="button"
            onClick={() => setActiveTab('assets')}
            className={`py-1 transition-colors whitespace-nowrap shrink-0 cursor-pointer border-b-2 ${
              activeTab === 'assets'
                ? 'text-amber-300 border-amber-400 font-semibold'
                : 'border-transparent hover:text-slate-100'
            }`}
          >
            资产与代理治理
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('color')}
            className={`py-1 transition-colors whitespace-nowrap shrink-0 cursor-pointer border-b-2 ${
              activeTab === 'color'
                ? 'text-amber-300 border-amber-400 font-semibold'
                : 'border-transparent hover:text-slate-100'
            }`}
          >
            编码与色彩科学
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('diagnostics')}
            className={`py-1 transition-colors whitespace-nowrap shrink-0 cursor-pointer border-b-2 ${
              activeTab === 'diagnostics'
                ? 'text-amber-300 border-amber-400 font-semibold'
                : 'border-transparent hover:text-slate-100'
            }`}
          >
            故障排错与热监控
          </button>
          <button
            type="button"
            onClick={() => setActiveTab('assistant')}
            className={`py-1 transition-colors whitespace-nowrap shrink-0 cursor-pointer border-b-2 ${
              activeTab === 'assistant'
                ? 'text-amber-300 border-amber-400 font-semibold'
                : 'border-transparent hover:text-slate-100'
            }`}
          >
            AI 总监级剪辑助理
          </button>
        </nav>

        {/* Zone 3: 1 Primary Action Button */}
        <div className="flex items-center shrink-0">
          <button
            type="button"
            onClick={() => setShowTurnoverModal(true)}
            className="px-4 py-2 text-xs font-semibold text-slate-950 bg-amber-400 hover:bg-amber-300 rounded-lg transition-colors whitespace-nowrap shrink-0 cursor-pointer"
          >
            导出交接规范单
          </button>
        </div>
      </header>

      {/* Contextual Workspace Status Strip (below fold of header) */}
      <div className="bg-slate-900/60 border-b border-slate-800/80 px-6 py-2.5">
        <div className="max-w-[1380px] mx-auto flex flex-wrap items-center justify-between gap-4 text-xs">
          <div className="flex flex-wrap items-center gap-2 text-slate-300 font-mono">
            <span>当前工程代号: {projectCode}</span>
            <span aria-hidden="true">·</span>
            <span>时间码基准: SMPTE 23.976 / 24.00 fps</span>
            <span aria-hidden="true">·</span>
            <span>音频规范: 48,000 Hz / 24-bit BWF</span>
          </div>

          <div className="flex flex-wrap items-center gap-3 font-mono tabular-nums">
            <span className="text-slate-400">
              工作站遥测: GPU {telemetry.gpuTempC}°C / CPU {telemetry.cpuTempC}°C / VRAM {hardwareSummary.vramUsagePercent}%
            </span>
            <span aria-hidden="true" className="text-slate-600">·</span>
            <button
              type="button"
              onClick={() => setActiveTab('diagnostics')}
              className={`underline underline-offset-4 cursor-pointer ${
                hardwareSummary.overallStatus === 'Nominal'
                  ? 'text-emerald-400'
                  : hardwareSummary.overallStatus === 'Warning'
                  ? 'text-amber-300'
                  : 'text-rose-400 font-semibold'
              }`}
            >
              状态: {hardwareSummary.overallStatus === 'Nominal' ? '温度与显存受控' : '查看硬件降频预警'}
            </button>
          </div>
        </div>
      </div>

      {/* Main Content Container */}
      <main className="flex-1 max-w-[1380px] w-full mx-auto px-6 py-8">
        {activeTab === 'assets' && (
          <AssetGovernanceView projectCode={projectCode} onProjectCodeChange={setProjectCode} />
        )}
        {activeTab === 'color' && <ColorAndCodecView />}
        {activeTab === 'diagnostics' && (
          <DiagnosticsAndThermalView telemetry={telemetry} onTelemetryChange={setTelemetry} />
        )}
        {activeTab === 'assistant' && (
          <AiAssistantView projectCode={projectCode} telemetry={telemetry} />
        )}
      </main>

      {/* Clean Quiet Footer */}
      <footer className="border-t border-slate-800/80 px-6 py-5 text-xs text-slate-400">
        <div className="max-w-[1380px] mx-auto flex flex-col sm:flex-row items-center justify-between gap-4">
          <div>
            CutLine Post-Production Assistant Workbench · 面向好莱坞长片与一线TVC广告工业流程标准
          </div>
          <div className="flex items-center gap-4">
            <button
              type="button"
              onClick={() => setActiveTab('assets')}
              className="hover:text-slate-200 transition-colors cursor-pointer"
            >
              资产命名规范
            </button>
            <span aria-hidden="true">·</span>
            <button
              type="button"
              onClick={() => setActiveTab('color')}
              className="hover:text-slate-200 transition-colors cursor-pointer"
            >
              ACES 1.3 色彩管线
            </button>
            <span aria-hidden="true">·</span>
            <button
              type="button"
              onClick={() => setShowTurnoverModal(true)}
              className="hover:text-slate-200 transition-colors cursor-pointer"
            >
              XML / AAF 套底交接单
            </button>
          </div>
        </div>
      </footer>

      {/* Turnover Spec Sheet Modal */}
      {showTurnoverModal && (
        <div
          role="dialog"
          aria-modal="true"
          aria-labelledby="turnover-modal-title"
          className="fixed inset-0 z-50 bg-black/75 flex items-center justify-center p-4"
        >
          <div className="bg-slate-900 border border-slate-700 rounded-xl max-w-2xl w-full p-6 shadow-2xl space-y-4">
            <div className="flex items-center justify-between gap-4 border-b border-slate-800 pb-3">
              <div>
                <h2 id="turnover-modal-title" className="text-base font-semibold text-slate-100">
                  工业套底与后期交接规范单 ({projectCode} Turnover Spec)
                </h2>
                <p className="text-xs text-slate-400">
                  可直接随附于发往 DI 调色房、Pro Tools 混音棚或 VFX 视效团队的交接目录中
                </p>
              </div>
              <button
                type="button"
                aria-label="关闭交接规范单弹窗"
                onClick={() => setShowTurnoverModal(false)}
                className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <pre className="bg-slate-950 border border-slate-800 rounded-lg p-4 text-xs font-mono text-slate-200 overflow-x-auto max-h-[380px] leading-relaxed">
              {turnoverDocument}
            </pre>

            <div className="flex items-center justify-end gap-3 pt-2">
              <button
                type="button"
                onClick={handleCopyTurnover}
                className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-medium bg-slate-800 hover:bg-slate-700 text-slate-100 rounded-lg transition-colors cursor-pointer"
              >
                {copiedTurnover ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copiedTurnover ? '已复制到剪贴板' : '复制规范文本'}</span>
              </button>
              <button
                type="button"
                onClick={handleDownloadTurnover}
                className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold bg-amber-400 hover:bg-amber-300 text-slate-950 rounded-lg transition-colors cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>下载 .TXT 交接单</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
